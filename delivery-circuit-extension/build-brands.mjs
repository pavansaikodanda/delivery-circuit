// Monochrome app logos for the webview kit (design/DESIGN.md §3.2). Used by build.mjs (writes media/shared/brands.js)
// and by the preview harness when the build has not run yet. Build-time only: the package is a devDependency.
import fs from "node:fs";
import path from "node:path";

/** DC.brand ids -> simple-icons export names. Slack, Salesforce and Fireflies are not in the package: DC.brand falls
 *  back to codicons for them, so they are not listed here. */
export const BRAND_EXPORTS = {
  github: "siGithub", jira: "siJira", confluence: "siConfluence", atlassian: "siAtlassian", lucid: "siLucid",
  coderabbit: "siCoderabbit", claude: "siClaude", anthropic: "siAnthropic",
};

export async function brandsJs(root) {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, "node_modules", "simple-icons", "package.json"), "utf8"));
  const si = await import("simple-icons");
  const out = {};
  for (const [id, name] of Object.entries(BRAND_EXPORTS)) {
    const icon = si[name];
    if (icon && typeof icon.path === "string" && icon.path) out[id] = { title: icon.title, path: icon.path };
    else console.warn(`simple-icons ${pkg.version}: ${name} not found; DC.brand("${id}") uses its codicon fallback`);
  }
  return `// Generated by build.mjs from simple-icons ${pkg.version} (${pkg.license}); do not edit.\n` +
    `// The SVG paths are copied unmodified; each brand's own guidelines apply (see simple-icons DISCLAIMER.md).\n` +
    `window.DC_BRANDS = ${JSON.stringify(out)};\n`;
}

export async function writeBrands(root) {
  const file = path.join(root, "media", "shared", "brands.js");
  fs.writeFileSync(file, await brandsJs(root));
  return file;
}
